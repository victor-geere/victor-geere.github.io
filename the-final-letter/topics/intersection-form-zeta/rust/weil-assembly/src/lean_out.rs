//! Writer for `lean/Certificate.lean`.
//!
//! The file contains only rational literals and the concrete instance check of
//! the generic box theorems (`ldl_posDef_rat`, `box_ge_rat`, `posDef_of_box_rat`)
//! from `Topic.lean`.  It contains no `sorry`, `axiom`, `native_decide` or
//! floating-point literal.

use crate::assemble::Assembly;
use crate::rational::lean_rat;
use rug::Rational;

fn mat(name: &str, m: &[[Rational; 4]; 4], comment: &str) -> String {
    let mut arms = String::new();
    for i in 0..4 {
        for j in 0..4 {
            arms.push_str(&format!(
                "  | {}, {} => {}\n",
                i,
                j,
                lean_rat(&m[i][j])
            ));
        }
    }
    format!(
        "/-- {comment} -/\ndef {name} : Matrix (Fin 4) (Fin 4) ℚ\n{arms}  | _, _ => 0\n"
    )
}

fn vec(name: &str, v: &[Rational; 4], comment: &str) -> String {
    let mut arms = String::new();
    for (i, q) in v.iter().enumerate() {
        arms.push_str(&format!("  | {} => {}\n", i, lean_rat(q)));
    }
    format!("/-- {comment} -/\ndef {name} : Fin 4 → ℚ\n{arms}")
}

const THEOREMS: &str = r#"
theorem certD_pos : ∀ i, 0 < certD i := by
  intro i
  fin_cases i <;> norm_num [certD]

theorem certL_lower : certL.IsLowerTriangular := by decide

theorem certL_det : certL.det = 1 := by
  rw [Matrix.det_of_isLowerTriangular certL certL_lower, Fin.prod_univ_four]
  norm_num [certL]

theorem certL_unit : IsUnit certL := by
  rw [Matrix.isUnit_iff_isUnit_det, certL_det]
  exact isUnit_one

theorem cert_factor : certL * diagonal certD * certLᴴ = certP := by
  ext i j
  fin_cases i <;> fin_cases j <;>
    norm_num [certL, certD, certP, certG0, certT, Matrix.mul_apply,
      Matrix.diagonal, Matrix.conjTranspose, Matrix.transpose,
      Fin.sum_univ_four]

theorem certP_posDef : certP.PosDef := by
  have h := ldl_posDef_rat (L := certL) (d := certD) certD_pos certL_unit
  rwa [cert_factor] at h

"#;

const CONCRETE: &str = r#"
theorem certA_herm : certA.IsHermitian := by
  ext i j
  fin_cases i <;> fin_cases j <;> norm_num [certA]

theorem certA_mem_box :
    ∀ i j, |certA i j - (certP + certT • 1) i j| ≤ certE i j := by
  intro i j
  fin_cases i <;> fin_cases j <;>
    norm_num [certA, certP, certG0, certE, certT]

theorem certE_row : ∀ i, ∑ j, certE i j ≤ certT := by
  intro i
  fin_cases i <;> norm_num [certE, certT, Fin.sum_univ_four]

theorem certA_posDef : certA.PosDef :=
  posDef_of_box_rat certA_herm certP_posDef certE_row certA_mem_box

end IntersectionForm
"#;

pub fn write_lean(a: &Assembly) -> String {
    let mut out = String::new();
    out.push_str(
        r#"import Topic

/-!
# Generated rational certificate for the `4 × 4` Weil Gram box

Generated by `rust/weil-assembly`.  `certG0` is the centre of the interval
Gram matrix, `certE` the entrywise half-widths (including the `10⁻⁴` margin),
`certT` the row-sum operator slack, and `certL`, `certD`, `certP` the exact
rational `LDLᵀ` factorisation of `certP = certG0 − certT • 1`.  `certA` is a
distinct 12-digit numerical matrix inside the box, so the final theorem is a
genuine instance check rather than a restatement of the centre.

Every proof below is checked by the kernel; there are no placeholders and no
floating-point literals.
-/

open Matrix
open scoped BigOperators

namespace IntersectionForm

"#,
    );
    out.push_str(&mat(
        "certG0",
        &a.centre,
        "Centre matrix `G₀` of the certified interval Gram matrix (4×4, rational).",
    ));
    out.push('\n');
    out.push_str(&mat(
        "certE",
        &a.err,
        "Entrywise half-widths `E` of the certified box (4×4, rational, nonnegative).",
    ));
    out.push('\n');
    out.push_str(&format!(
        "/-- Operator slack `t = max_i Σ_j E_ij + 10⁻⁹`. -/\ndef certT : ℚ := {}\n\n",
        lean_rat(&a.t)
    ));
    out.push_str(
        "/-- `P = G₀ − t • 1`, the matrix whose positive definiteness is certified. -/\n\
         def certP : Matrix (Fin 4) (Fin 4) ℚ :=\n  certG0 - certT • (1 : Matrix (Fin 4) (Fin 4) ℚ)\n\n",
    );
    out.push_str(&mat(
        "certL",
        &a.ldl_l,
        "Unit lower-triangular factor `L` of the exact `LDLᵀ` decomposition of `certP`.",
    ));
    out.push('\n');
    out.push_str(&vec(
        "certD",
        &a.ldl_d,
        "Positive diagonal `D` of the exact `LDLᵀ` decomposition of `certP`.",
    ));
    out.push_str(THEOREMS);
    out.push_str(&mat(
        "certA",
        &a.numerical,
        "A 12-digit numerical matrix inside the certified box (rows/columns match `certG0`).",
    ));
    out.push_str(CONCRETE);
    out
}
