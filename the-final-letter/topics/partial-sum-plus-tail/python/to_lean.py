#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
012/rigorous/to_lean.py — turn a `partial-sum-plus-tail` certificate into a Lean
replay (`012/lean/Replay.lean`) for the checked cell `Expr.lean`.

Usage:
    python3 to_lean.py cert.json 012/lean/Replay.lean

The certificate DAG is expanded into an `Expr` term (shared subtrees are
duplicated, so keep the certificate small: `M <= 6`, `K <= 3`, `bits <= 56`).

Every atom becomes a leaf `Expr.atom i (A i)`; the atom boxes are emitted as
`def A : Nat → Cx`.  The generated file ends with

    example : cert.wf A = true := by decide
    theorem cert_mem {σ : Nat → ℂ} (h : ∀ i, Cx.mem (σ i) (A i)) :
        Cx.mem (cert.eval σ) cert.box := Expr.wf_sound h cert (by decide)

so the rational cell is kernel-checked, and the only hypotheses are the atom
memberships (discharged numerically by `verify_certificate.py`).
"""
from __future__ import annotations

import json
import sys
from fractions import Fraction as F


def _rat(x) -> str:
    f = F(x)
    if f.denominator == 1:
        return f"({f.numerator} : ℚ)"
    return f"(({f.numerator} : ℚ) / {f.denominator})"


def _box(j) -> str:
    re_lo, re_hi = j["re"]
    im_lo, im_hi = j["im"]
    return (f"⟨⟨{_rat(re_lo)}, {_rat(re_hi)}⟩, "
            f"⟨{_rat(im_lo)}, {_rat(im_hi)}⟩⟩")


class Gen:
    def __init__(self, cert: dict):
        self.cert = cert
        self.atoms = {a["id"]: a for a in cert["atoms"]}
        self.ops = {o["out"]: o for o in cert["ops"]}
        self.atom_index = {}
        n = 0
        for a in cert["atoms"]:
            if a["kind"] != "opaque":
                self.atom_index[a["id"]] = n
                n += 1
        self.n_atoms = n
        self.size = 0

    def expand(self, nid: int, memo=None) -> str:
        self.size += 1
        if nid in self.atom_index:
            i = self.atom_index[nid]
            return f"(Expr.atom {i} {_box(self.atoms[nid]['box'])})"
        a = self.atoms.get(nid)
        if a is not None:                       # opaque atom: treat as leaf too
            i = self.atom_index.get(nid)
            if i is None:
                self.atom_index[nid] = self.n_atoms
                i = self.n_atoms
                self.n_atoms += 1
            return f"(Expr.atom {i} {_box(a['box'])})"
        op = self.ops[nid]
        name = op["op"]
        box = _box(op["box"])
        ins = op["in"]
        if name in ("add", "sub", "mul"):
            return f"(Expr.{name} {box} {self.expand(ins[0])} {self.expand(ins[1])})"
        if name == "neg":
            return f"(Expr.neg {box} {self.expand(ins[0])})"
        if name == "scale":
            return f"(Expr.scale {box} {_rat(op['scalar'])} {self.expand(ins[0])})"
        if name == "inflate":
            return f"(Expr.inflate {box} {_rat(op['scalar'])} {self.expand(ins[0])})"
        raise ValueError(f"unknown op {name!r}")


def main(argv) -> int:
    cert_path, out_path = argv[1], argv[2]
    ns = argv[3] if len(argv) > 3 else "Replay"
    with open(cert_path) as fh:
        cert = json.load(fh)
    g = Gen(cert)
    body = g.expand(cert["final"])

    # atom boxes A : Nat -> Cx
    A_lines = []
    for nid, i in sorted(g.atom_index.items(), key=lambda kv: kv[1]):
        a = g.atoms[nid] if nid in g.atoms else None
        box = (a["box"] if a is not None
               else None)
        if box is None:
            # find in ops? atoms only
            raise ValueError(f"atom {nid} missing")
        A_lines.append((i, a.get("label", "?"), box))

    lines = []
    lines.append("/- GENERATED by 012/rigorous/to_lean.py — do not edit by hand. -/")
    lines.append("import Expr")
    lines.append("")
    lines.append(f"namespace PartialTail.{ns}")
    lines.append("")
    lines.append("open PartialTail PartialTail.Expr")
    lines.append("")
    lines.append(f"-- certificate: {cert.get('function')} {cert.get('params')}")
    lines.append(f"-- atoms = {g.n_atoms}, expanded tree nodes = {g.size}")
    lines.append("")
    lines.append("def A : Nat → Cx")
    for i, label, box in A_lines:
        lines.append(f"  | {i} => {_box(box)}   -- {label}")
    lines.append("  | _ => ⟨⟨0, 0⟩, ⟨0, 0⟩⟩")
    lines.append("")
    lines.append("def cert : Expr :=")
    lines.append("  " + body)
    lines.append("")
    lines.append("/-- The checker accepts this certificate. -/")
    lines.append("example : cert.wf A = true := by native_decide")
    lines.append("")
    lines.append("/-- Consequence: the denoted value lies in the final box. -/")
    lines.append("theorem cert_mem {σ : Nat → ℂ} (h : ∀ i, Cx.mem (σ i) (A i)) :")
    lines.append("    Cx.mem (cert.eval σ) cert.box :=")
    lines.append("  Expr.wf_sound h cert (by native_decide)")
    lines.append("")
    lines.append(f"end PartialTail.{ns}")
    lines.append("")

    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    print(f"wrote {out_path}: {g.n_atoms} atoms, tree size {g.size}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
